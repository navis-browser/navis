import { readFile, writeFile } from "node:fs/promises";
import { createIcon } from "../product/chrome/content/design-system.mjs";
import { EN_US_MESSAGES } from "../product/chrome/content/locales/en-US.mjs";
import { ZH_CN_MESSAGES } from "../product/chrome/content/locales/zh-CN.mjs";

const check = process.argv[2] === "--check";
if (!check && process.argv[2] !== "--write") throw new Error("Use --check or --write");
const root = new URL("../android/src/main/res/", import.meta.url);
const xml = value => String(value).replaceAll("&", "&amp;").replaceAll('"', "&quot;")
  .replaceAll("<", "&lt;").replaceAll(">", "&gt;");
const generated = '<!-- Generated by scripts/sync-android-site-presentation.mjs; edit the desktop source. -->';

async function output(path, value) {
  const url = new URL(path, root);
  if (check) {
    if (await readFile(url, "utf8") !== value) throw new Error(`Desktop/Android presentation drift: ${path}`);
  } else await writeFile(url, value);
}

const keys = Object.keys(EN_US_MESSAGES).filter(key => key.startsWith("siteInfo.") ||
  key.startsWith("certificate.") || key === "common.unavailable" || key === "app.name").sort();
for (const [directory, messages] of [["values", EN_US_MESSAGES], ["values-zh-rCN", ZH_CN_MESSAGES]]) {
  const rows = keys.map(key => {
    if (typeof messages[key] !== "string") throw new Error(`Missing ${directory} ${key}`);
    let position = 0;
    const value = messages[key].replaceAll("\\", "\\\\").replaceAll("'", "\\'")
      .replace(/\{[a-zA-Z]+\}/gu, () => `%${++position}$s`);
    return `    <string name="site_desktop_${key.replaceAll(".", "_").toLowerCase()}">${xml(value)}</string>`;
  });
  await output(`${directory}/site_presentation_strings.xml`,
    `<?xml version="1.0" encoding="utf-8"?>\n${generated}\n<resources>\n${rows.join("\n")}\n</resources>\n`);
}

const css = await readFile(new URL("../product/chrome/content/design-system.css", import.meta.url), "utf8");
const style = css.match(/\.navis-icon\s*\{([^}]+)\}/u)?.[1] ?? "";
const stroke = style.match(/stroke-width:\s*([\d.]+);/u)?.[1];
if (!stroke || !style.includes("stroke-linecap: round;") || !style.includes("stroke-linejoin: round;")) {
  throw new Error("Review changed desktop icon drawing semantics before regenerating Android vectors");
}
const document = {
  createElementNS(_namespace, name) {
    return { name, attributes: {}, children: [], classList: { add() {} },
      setAttribute(key, value) { this.attributes[key] = value; },
      append(child) { this.children.push(child); } };
  },
};
// The Navis brand mark is a shared masked silhouette, generated by sync-android-brand.mjs.
// It is not one of the desktop UI's generic 20px stroke icons.
const iconNames = { controls: "siteControls", extension: "extension",
  warning: "warning", info: "info", certificate: "certificate", back: "back", close: "close" };
for (const [file, name] of Object.entries(iconNames)) {
  const icon = createIcon(document, name);
  if (icon.attributes.viewBox !== "0 0 20 20") throw new Error("Review changed desktop icon viewport");
  const paths = icon.children.map(({ name: element, attributes: a }) => {
    let path;
    if (element === "path") path = a.d;
    else if (element === "circle") {
      const [x, y, r] = [a.cx, a.cy, a.r].map(Number);
      if (![x, y, r].every(Number.isFinite) || r <= 0) throw new Error("Invalid circle");
      path = `M${x - r} ${y}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
    } else throw new Error(`Unsupported desktop geometry: ${element}`);
    const filled = a.class === "icon-fill";
    const paint = filled ? 'android:fillColor="#FF000000"' :
      `android:fillColor="@android:color/transparent" android:strokeColor="#FF000000" android:strokeWidth="${stroke}" android:strokeLineCap="round" android:strokeLineJoin="round"`;
    return `    <path ${paint} android:pathData="${xml(path)}" />`;
  });
  await output(`drawable/ic_site_${file}.xml`,
    `<?xml version="1.0" encoding="utf-8"?>\n${generated}\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="20dp" android:height="20dp" android:viewportWidth="20" android:viewportHeight="20">\n${paths.join("\n")}\n</vector>\n`);
}
process.stdout.write(`Android site presentation ${check ? "matches" : "generated from"} desktop messages and vector geometry.\n`);
