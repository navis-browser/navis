// Android vectors cannot evaluate SVG feDropShadow filters. Preserve all geometry,
// gradients/frost/rim; map relief to the same translated alpha strokes, without blur.
// Monochrome PNGs use the shared SVG mask so seams are transparent, not white paint.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const check = process.argv[2] === "--check";
if (!check && process.argv[2] !== "--write") throw new Error("Use --check or --write");
const root = new URL("../", import.meta.url);
const mark = JSON.parse(await readFile(new URL("product/branding/navis-mark.json", root), "utf8"));
if (mark.schemaVersion !== 1) throw new Error("Review changed shared brand schema");
const generated = "Generated by scripts/sync-android-brand.mjs from product/branding/navis-mark.json; do not edit.";
const ns = 'xmlns:android="http://schemas.android.com/apk/res/android"';
const xml = text => String(text).replaceAll("&", "&amp;").replaceAll('"', "&quot;");
const number = value => Number(value.toFixed(6)).toString();
const color = (value, alpha = 1) => `#${Math.round(alpha * 255).toString(16).padStart(2, "0")}${value.slice(1)}`.toUpperCase();
const contour = (radius = mark.contour.rx) => {
  const { x, y, width: w, height: h } = mark.contour;
  return `M${x + radius},${y} H${x + w - radius} A${radius},${radius} 0 0 1 ${x + w},${y + radius} V${y + h - radius} A${radius},${radius} 0 0 1 ${x + w - radius},${y + h} H${x + radius} A${radius},${radius} 0 0 1 ${x},${y + h - radius} V${y + radius} A${radius},${radius} 0 0 1 ${x + radius},${y} Z`;
};
function absoluteGradient(name) {
  const gradient = mark.gradients[name];
  if (gradient.units === "userSpaceOnUse") return gradient;
  const { x, y, width: w, height: h } = mark.contour;
  return gradient.type === "radial"
    ? { ...gradient, cx: x + w * gradient.cx, cy: y + h * gradient.cy, r: w * gradient.r }
    : { ...gradient, x1: x + w * gradient.x1, y1: y + h * gradient.y1,
      x2: x + w * gradient.x2, y2: y + h * gradient.y2 };
}
function gradient(name, attribute = "fillColor") {
  const g = absoluteGradient(name);
  const coordinates = g.type === "radial"
    ? `android:centerX="${number(g.cx)}" android:centerY="${number(g.cy)}" android:gradientRadius="${number(g.r)}"`
    : `android:startX="${number(g.x1)}" android:startY="${number(g.y1)}" android:endX="${number(g.x2)}" android:endY="${number(g.y2)}"`;
  return `<aapt:attr name="android:${attribute}"><gradient android:type="${g.type}" ${coordinates}>${g.stops.map(stop =>
    `<item android:color="${color(stop.color, stop.opacity ?? 1)}" android:offset="${stop.offset}" />`).join("")}</gradient></aapt:attr>`;
}
function stroke(path, width, paint, alpha = 1) {
  const child = paint.startsWith("<") ? paint : "";
  return `<path android:pathData="${xml(path)}" android:fillColor="@android:color/transparent" android:strokeWidth="${width}" android:strokeLineCap="round" android:strokeLineJoin="round" android:strokeAlpha="${alpha}"${child ? "" : ` android:strokeColor="${paint}"`}>${child}</path>`;
}
function relief(path, width, kind) {
  return mark.effects.relief[kind].shadows.map(shadow =>
    `<group android:translateX="${shadow.dx}" android:translateY="${shadow.dy}">${stroke(path, width, color(shadow.color), shadow.opacity)}</group>`).join("\n");
}
function contourRelief(path) {
  return mark.effects.relief.contour.shadows.map(shadow =>
    `<group android:translateX="${shadow.dx}" android:translateY="${shadow.dy}"><path android:pathData="${xml(path)}" android:fillColor="${color(shadow.color)}" android:fillAlpha="${shadow.opacity}" /></group>`).join("\n");
}
function vector(radius = mark.contour.rx, adaptive = false) {
  const shape = contour(radius);
  const viewport = adaptive ? 108 : mark.viewBox[2];
  // The complete 176-unit mark occupies the central 66dp safe region of 108dp.
  const unit = 66 / mark.contour.width;
  const shift = 54 - mark.transform.cx * unit;
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${generated} -->\n` +
    `<vector ${ns} xmlns:aapt="http://schemas.android.com/aapt" android:width="108dp" android:height="108dp" android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">\n` +
    (adaptive ? `<group android:scaleX="${unit}" android:scaleY="${unit}" android:translateX="${shift}" android:translateY="${shift}">\n` : "") +
    `<group><clip-path android:pathData="${shape}" />\n` +
    contourRelief(shape) + "\n" +
    ["contour", "frostDiffuse", "frostFog"].map(name => `<path android:pathData="${shape}">${gradient(name)}</path>`).join("\n") +
    `\n${stroke(shape, mark.effects.rim.strokeWidth, gradient("rim", "strokeColor"), mark.effects.rim.opacity)}\n` +
    `<group android:rotation="${mark.transform.rotate}" android:pivotX="${mark.transform.cx}" android:pivotY="${mark.transform.cy}">\n` +
    relief(mark.channel.path, mark.channel.strokeWidth, "channel") + "\n" +
    stroke(mark.channel.path, mark.channel.strokeWidth, gradient("channel", "strokeColor"), mark.channel.opacity) + "\n" +
    mark.seams.paths.map(path => relief(path, mark.seams.strokeWidth, "seam") + "\n" +
      stroke(path, mark.seams.strokeWidth, color(mark.seams.color))).join("\n") +
    `\n</group></group>${adaptive ? "</group>" : ""}\n</vector>\n`;
}
async function output(path, bytes) {
  const url = new URL(path, root);
  if (check) {
    const actual = await readFile(url);
    if (!actual.equals(Buffer.from(bytes))) throw new Error(`Shared/Android brand drift: ${path}`);
  } else {
    await mkdir(dirname(fileURLToPath(url)), { recursive: true });
    await writeFile(url, bytes);
  }
}
const res = "android/src/main/res/";
await output(`${res}drawable/ic_navis_brand.xml`, vector());
await output(`${res}drawable/ic_navis_brand_round.xml`, vector(mark.contourVariants.circle));
await output(`${res}drawable/ic_navis_adaptive_foreground.xml`, vector(mark.contour.rx, true));
await output(`${res}values/navis_brand_colors.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${generated} -->\n<resources><color name="navis_launcher_background">${mark.gradients.contour.stops[1].color}</color></resources>\n`);
for (const [name, legacy] of [["ic_navis_launcher", "ic_navis_brand"], ["ic_navis_launcher_round", "ic_navis_brand_round"]]) {
  await output(`${res}mipmap-anydpi/${name}.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${generated} -->\n<layer-list ${ns}><item android:drawable="@drawable/${legacy}" /></layer-list>\n`);
  for (const api of [26, 33]) {
    await output(`${res}mipmap-anydpi-v${api}/${name}.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${generated} -->\n<adaptive-icon ${ns}><background android:drawable="@color/navis_launcher_background" /><foreground android:drawable="@drawable/ic_navis_adaptive_foreground" />${api >= 33 ? '<monochrome android:drawable="@drawable/ic_navis_adaptive_monochrome" />' : ""}</adaptive-icon>\n`);
  }
}

const float = value => `${number(value)}f`;
const cf = mark.motion.counterflow;
const comet = mark.motion.comet;
const constants = {
  VIEWPORT: mark.viewBox[2], CORNER_RADIUS: mark.contour.rx, ROTATION: mark.transform.rotate,
  CONTOUR_X: mark.contour.x, CONTOUR_Y: mark.contour.y, CONTOUR_WIDTH: mark.contour.width,
  CONTOUR_HEIGHT: mark.contour.height, CENTER_X: mark.transform.cx, CENTER_Y: mark.transform.cy,
  CHANNEL_WIDTH: mark.channel.strokeWidth, CHANNEL_OPACITY: mark.channel.opacity,
  SEAM_WIDTH: mark.seams.strokeWidth, SEAM_DASH: cf.seamDashLength,
  BASE_MILLISECONDS: cf.contourDurationMs, BASE_OPAQUE_AT: cf.contourOpaqueAt,
  SEAM_DELAY_MILLISECONDS: cf.seamDelayMs, SEAM_MILLISECONDS: cf.seamDurationMs,
  INTRO_MILLISECONDS: comet.delayMs, HEAD_MILLISECONDS: comet.headDurationMs,
  PARTICLE_MILLISECONDS: comet.particleDurationMs, OVERLAY_MILLISECONDS: comet.overlayDurationMs,
  OVERLAY_INITIAL_SCALE: comet.overlayInitialScale, HEAD_RADIUS: comet.headRadius,
  RIM_WIDTH: mark.effects.rim.strokeWidth, RIM_OPACITY: mark.effects.rim.opacity,
};
const rows = Object.entries(constants).map(([key, value]) => `    const val ${key} = ${float(value)}`);
for (const [key, value] of Object.entries({ CHANNEL: mark.channel.path, SEAM_A: mark.seams.paths[0], SEAM_B: mark.seams.paths[1] })) {
  rows.push(`    const val ${key} = ${JSON.stringify(value)}`);
}
for (const [key, values] of Object.entries({ BASE_EASING: cf.contourEasing, SEAM_EASING: cf.seamEasing,
  HEAD_EASING: comet.headEasing, HEAD_SCALE: comet.headScale, HEAD_KEY_TIMES: comet.headKeyTimes })) {
  rows.push(`    val ${key} = floatArrayOf(${values.map(float).join(", ")})`);
}
for (const name of Object.keys(mark.gradients)) {
  const g = absoluteGradient(name);
  const key = name.replace(/[A-Z]/g, letter => `_${letter}`).toUpperCase();
  rows.push(`    val ${key}_COLORS = longArrayOf(${g.stops.map(stop => `0x${color(stop.color, stop.opacity ?? 1).slice(1)}`).join(", ")})`);
  rows.push(`    val ${key}_STOPS = floatArrayOf(${g.stops.map(stop => float(stop.offset)).join(", ")})`);
  rows.push(`    val ${key}_POSITION = floatArrayOf(${(g.type === "radial" ? [g.cx, g.cy, g.r] : [g.x1, g.y1, g.x2, g.y2]).map(float).join(", ")})`);
}
rows.push(`    val particles = listOf(\n${comet.particles.map(particle => `        Particle(floatArrayOf(${particle.offsets.map(float).join(", ")}), ${float(particle.radius)}, ${float(particle.fillOpacity * comet.particleOpacity)}, floatArrayOf(${particle.keyPoints.map(float).join(", ")}), floatArrayOf(${particle.keyTimes.map(float).join(", ")}), floatArrayOf(${particle.opacityValues.map(float).join(", ")}), floatArrayOf(${particle.opacityKeyTimes.map(float).join(", ")}))`).join(",\n")}\n    )`);
for (const [kind, details] of Object.entries(mark.effects.relief)) {
  rows.push(`    val ${kind}Relief = listOf(${details.shadows.map(s => `Relief(${float(s.dx)}, ${float(s.dy)}, 0x${color(s.color).slice(1)}, ${float(s.opacity)})`).join(", ")})`);
}
await output("android/src/main/java/org/navis/browser/ui/NavisBrandGeometry.kt",
  `// ${generated}\npackage org.navis.browser.ui\n\ninternal object NavisBrandGeometry {\n` +
  rows.join("\n") + "\n    data class Particle(val offsets: FloatArray, val radius: Float, val alpha: Float, val positions: FloatArray, val times: FloatArray, val opacities: FloatArray, val opacityTimes: FloatArray)\n    data class Relief(val x: Float, val y: Float, val color: Long, val alpha: Float)\n}\n");

const mono = await readFile(new URL("product/branding/generated/navis-mark-mono.svg", root), "utf8");
function raster(svg, size) {
  const result = spawnSync("rsvg-convert", ["--width", String(size), "--height", String(size)], { input: svg });
  if (result.status !== 0) throw new Error(`rsvg-convert failed: ${result.stderr?.toString()}`);
  return result.stdout;
}
for (const [density, size] of [["mdpi", 24], ["hdpi", 36], ["xhdpi", 48], ["xxhdpi", 72], ["xxxhdpi", 96]]) {
  await output(`${res}drawable-${density}/ic_navis_notification.png`, raster(mono, size));
}
const inner = mono.match(/<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/u)?.[1];
if (!inner) throw new Error("Cannot read shared monochrome SVG root");
const adaptiveUnit = 66 / mark.contour.width;
const adaptiveShift = 54 - mark.transform.cx * adaptiveUnit;
const adaptiveMono = `<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108"><g transform="translate(${adaptiveShift} ${adaptiveShift}) scale(${adaptiveUnit})">${inner}</g></svg>`;
await output(`${res}drawable-nodpi/ic_navis_adaptive_monochrome.png`, raster(adaptiveMono, 432));
process.stdout.write(`Android brand ${check ? "matches" : "generated from"} the shared source.\n`);
